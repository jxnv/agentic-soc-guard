"""
Zero-Hallucination System Prompts and ADS Templates for Autonomous SOC Triage Agent.
Enforces strict grounding on empirical telemetry and baseline queries.
"""
from __future__ import annotations

import json
from typing import Dict, Any, List

TRIAGE_SYSTEM_PROMPT = """You are an Autonomous Tier-1 SOC Triage Agent operating under strict Zero-Hallucination Guardrails.

YOUR MISSION:
Analyze the provided security alert against deterministic enterprise baseline data and enrichments to issue a high-confidence triage disposition.

ZERO-HALLUCINATION RULES:
1. ONLY reference entities, commands, IPs, filenames, and numbers explicitly present in the provided context.
2. DO NOT fabricate CVE numbers, external IP reputation lookups, or unobserved events.
3. If an indicator is unknown or absent, state "No historical telemetry observed" or "N/A".
4. Base your verdict strictly on the Baseline Deviation Principle:
   - Frequent routine activity (>50 occurrences in baseline for known service accounts) -> FALSE_POSITIVE
   - Zero baseline occurrences with suspicious shell or credential dump commands -> TRUE_POSITIVE
   - Inconclusive or ambiguous context -> SUSPICIOUS_FURTHER_INVESTIGATION

OUTPUT FORMAT REQUIREMENT:
You must output a single, valid JSON object strictly complying with the following schema:
{
  "alert_id": "string",
  "verdict": "TRUE_POSITIVE" | "FALSE_POSITIVE" | "SUSPICIOUS_FURTHER_INVESTIGATION",
  "confidence_score": float (between 0.00 and 1.00),
  "root_cause_analysis": "string explaining exact causality",
  "mitre_mapping": ["string", ...],
  "immediate_containment_action": "string or null",
  "analyst_investigation_notes": "string"
}
"""


def build_triage_prompt(
    alert_data: Dict[str, Any],
    iocs: Dict[str, Any],
    baseline_stats: Dict[str, Any],
    enrichment: Dict[str, Any],
) -> str:
    """Constructs the structured user prompt containing all grounded telemetry context."""
    return f"""### ALERT TO INVESTIGATE:
{json.dumps(alert_data, indent=2)}

### EXTRACTED IOCs (DETERMINISTIC PARSER):
{json.dumps(iocs, indent=2)}

### HISTORICAL BASELINE CONTEXT (SQLITE TELEMETRY DATABASE):
- Historical Occurrences of Command in 30 Days: {baseline_stats.get('historical_occurrences_30d', 0)}
- Is User an Authorized Service Account: {baseline_stats.get('is_known_service_account', False)}
- User Profile: {baseline_stats.get('user_activity_profile', 'Unknown')}
- Observed Baseline Deviations: {baseline_stats.get('deviations_observed', [])}

### DETERMINISTIC ENRICHMENTS:
- CIDR Breakdown: {json.dumps(enrichment.get('cidr_breakdown', {}))}
- Shannon Entropy Scores: {json.dumps(enrichment.get('shannon_entropy_scores', {}))}
- Flagged Heuristics: {enrichment.get('heuristics_flagged', [])}

Analyze the data above and produce the required JSON triage verdict. Output ONLY raw JSON. No introductory or trailing markdown.
"""


def format_ads_markdown_brief(
    alert_id: str,
    rule_name: str,
    verdict: str,
    confidence_score: float,
    root_cause: str,
    mitre_mapping: List[str],
    containment_action: str | None,
    analyst_notes: str,
    iocs: Dict[str, Any],
    baseline_stats: Dict[str, Any],
    enrichment: Dict[str, Any],
) -> str:
    """Formats an Alert Disposition System (ADS) compliant investigation report."""
    verdict_badge = {
        "TRUE_POSITIVE": "🚨 **CONFIRMED TRUE POSITIVE**",
        "FALSE_POSITIVE": "🟢 **BENIGN NOISE / FALSE POSITIVE**",
        "SUSPICIOUS_FURTHER_INVESTIGATION": "🟡 **SUSPICIOUS (ESCALATED FOR TIER-2 REVIEW)**",
    }.get(verdict, verdict)

    mitre_str = ", ".join(f"`{m}`" for m in mitre_mapping) if mitre_mapping else "None"
    action_str = containment_action or "No containment required (Auto-closing alert)."

    return f"""# Autonomous SOC Triage Dossier: {alert_id}
**Rule:** `{rule_name}` | **Generated By:** Agentic-SOC Autonomous Engine | **Standard:** ADS-Compliant

---

## 1. Executive Disposition
- **Verdict:** {verdict_badge}
- **Confidence Score:** `{confidence_score * 100:.1f}%`
- **MITRE ATLAS / ATT&CK Mapping:** {mitre_str}
- **Immediate Recommended Action:** {action_str}

---

## 2. Root Cause Analysis
{root_cause}

---

## 3. Evidence Matrix & Baseline Correlation
| Attribute | Observed in Alert | Historical Enterprise Baseline | Disposition Impact |
| :--- | :--- | :--- | :--- |
| **Command Execution** | `{', '.join(iocs.get('commands', [])) or 'N/A'}` | `{baseline_stats.get('historical_occurrences_30d', 0)}` occurrences in 30d | {'Baseline verified routine' if baseline_stats.get('historical_occurrences_30d', 0) > 20 else 'Out-of-distribution anomaly'} |
| **User Identity** | `{', '.join(iocs.get('usernames', [])) or 'N/A'}` | {'Authorized Service Account' if baseline_stats.get('is_known_service_account') else 'Standard / Unprivileged User'} | {'Low Risk Actor' if baseline_stats.get('is_known_service_account') else 'Potential Compromise'} |
| **Entropy Score** | `{json.dumps(enrichment.get('shannon_entropy_scores', {}))}` | Normal Range: `< 3.5` | {'High Obfuscation / DGA' if any(v > 3.6 for v in enrichment.get('shannon_entropy_scores', {}).values()) else 'Normal command entropy'} |

---

## 4. Extracted Indicators of Compromise (IOCs)
- **Commands:** `{iocs.get('commands', [])}`
- **IP Addresses:** `{iocs.get('ips', [])}`
- **User Accounts:** `{iocs.get('usernames', [])}`
- **Target Files / Paths:** `{iocs.get('file_paths', [])}`
- **Network CIDR Classification:** `{enrichment.get('cidr_breakdown', {})}`

---

## 5. Analyst Investigation Notes & Audit Trail
{analyst_notes}
"""
